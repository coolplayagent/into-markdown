pub(super) fn function(id: u16, arguments: Option<u8>) -> Result<(&'static str, usize)> {
    let index =
        FUNCTIONS.binary_search_by_key(&id, |entry| entry.0).map_err(|_| "unsupported-function")?;
    let (_, name, minimum, maximum) = FUNCTIONS[index];
    let count = match arguments {
        Some(count) if (minimum..=maximum).contains(&count) => count,
        None if minimum == maximum => minimum,
        _ => return Err("unsupported-function-arity"),
    };
    Ok((name, usize::from(count)))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn function_signatures_are_sorted_and_bounded_and_unknown_calls_stay_unsupported() {
        assert!(FUNCTIONS.windows(2).all(|pair| pair[0].0 < pair[1].0));
        for &(id, name, minimum, maximum) in FUNCTIONS {
            assert!(minimum <= maximum && maximum <= 30);
            assert_eq!(function(id, Some(minimum)), Ok((name, usize::from(minimum))));
            assert_eq!(function(id, Some(maximum)), Ok((name, usize::from(maximum))));
            assert!(function(id, Some(maximum + 1)).is_err());
            if minimum == maximum {
                assert_eq!(function(id, None), Ok((name, usize::from(minimum))));
            }
        }
        assert_eq!(function(255, Some(1)), Err("unsupported-function"));
    }
}
